    n = lat_lon_alt.shape[0]

    order = 27

    egm = GravitationalPotential.EGM2008(order)
    earth = Earth.WGS84Ellipsoid()

    for i in range(n):
        lat = np.deg2rad(lat_lon_alt[i, 0])
        lon = np.deg2rad(lat_lon_alt[i, 1])
        alt = lat_lon_alt[i, 2]

        x, y, z = earth.cartesian_from_lat_lon_alt(lat, lon, alt)

        _, gx, gy, gz = egm.calculate(x, y, z)

        assert abs(gx - answers[i, 0]) < 1e-10
        assert abs(gy - answers[i, 1]) < 1e-10
        assert abs(gz - answers[i, 2]) < 1e-10
